/**
 * Pure types of the user-model domain: the ONE home of the `user-model`
 * message source, the three `user-model/*` session-event declarations, and
 * the `userModel` projection-key declaration, free of this package's host-side
 * imports. Two namespace projections serve it — `./types` for host consumers,
 * `./client` for client aggregates — with zero content duplication.
 *
 * @module @deepseek-ai/dsh-user-model/types
 */

import type { Message } from '@deepseek-ai/dsh-llm'

/**
 * The armed user-model: model route plus the human's goal text. The prompt is
 * the contract the user-model steers toward and judges completion against; it
 * rides the durable `user-model/armed` event so every armed read — driver,
 * apiproxy forwarding, projection, cold resume — folds the same fact.
 */
export interface UserModelSelection {
  /** Provider id of the user-model route. */
  readonly provider: string
  /** Model id of the user-model route. */
  readonly model: string
  /** The human's goal text: what the user-model drives the agent toward. */
  readonly prompt: string
}

/** Why the user-model disarmed. */
export type UserModelDisarmReason =
  /** The human explicitly disarmed (or re-armed, replacing the selection). */
  | 'user'
  /** The user-model declared the goal complete. */
  | 'complete'
  /** The agent's last turn ended aborted or errored. */
  | 'turn-failed'
  /** A user-model generation call failed or produced unusable output. */
  | 'generation-failed'
  /** The driver reached its configured per-arming reply cap. */
  | 'replies-exhausted'

/**
 * Marker the user-model emits — as the whole reply or on its own trailing
 * line — to declare the goal complete. Parsers strip it before delivery.
 */
export const USER_MODEL_COMPLETE_MARKER = '<task-complete/>'

/**
 * Provenance of a user-role message generated by the user-model: the exact
 * route that wrote it, so the conversation attributes synthetic user turns to
 * their real producer.
 */
export interface UserModelMessageSource {
  readonly kind: 'user-model'
  /** Provider of the user-model route that generated the message. */
  readonly provider: string
  /** Model of the user-model route that generated the message. */
  readonly model: string
}

/** Durable record of an arming: the user-model in force from this event until the next `user-model/disarmed`. */
export interface UserModelArmedEventData {
  readonly provider: string
  readonly model: string
  readonly prompt: string
}

/** Durable record of a disarming. */
export interface UserModelDisarmedEventData {
  readonly reason: UserModelDisarmReason
}

/** Which interaction one auxiliary user-model call serves. */
export type UserModelRequestPurpose =
  /** The stalled-loop steering reply the driver delivers as a user message. */
  | 'steer'
  /** An answer to the agent's pending user questions. */
  | 'question'
  /** A verdict on the agent's pending approval request. */
  | 'approval'

/**
 * Log-only pre-dispatch record of one user-model request — the exact system
 * prompt and role-flipped transcript the auxiliary call consumed, so the
 * model-visible boundary is auditable from the log alone.
 */
export interface UserModelRequestEventData {
  readonly purpose: UserModelRequestPurpose
  /** Provider of the route the request dispatched on. */
  readonly provider: string
  /** Model of the route the request dispatched on. */
  readonly model: string
  /** Exact auxiliary system prompt. */
  readonly system: string
  /** Exact auxiliary message list. */
  readonly messages: readonly Message[]
}

declare module '@deepseek-ai/dsh-llm' {
  interface MessageSourceMap {
    'user-model': UserModelMessageSource
  }
}

declare module '@deepseek-ai/dsh-session/types' {
  interface SessionEventMap {
    /** Log-only record of arming the user-model with a route and goal prompt. */
    'user-model/armed': UserModelArmedEventData
    /** Log-only record of disarming the user-model. */
    'user-model/disarmed': UserModelDisarmedEventData
    /** Log-only pre-dispatch record of one auxiliary user-model request. */
    'user-model/request': UserModelRequestEventData
  }
}

declare module '@deepseek-ai/dsh-session-projection/types' {
  interface SessionProjectionMap {
    /** Armed user-model selection folded from `user-model/armed` / `user-model/disarmed`; null while disarmed. */
    userModel: UserModelProjection
  }
}

/** The user-model projection's wire value: the armed selection, or null while disarmed. */
export type UserModelProjection = UserModelSelection | null
